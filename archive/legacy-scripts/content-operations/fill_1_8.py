HINTS = {"antonym":"ضد / متعاكس","plural":"جمع الكلمة","synonym":"مترادف","comprehension":"استيعاب قرائي"}

async def run():
    async with AsyncSessionLocal() as db:
        units = {u.unit_number: u for u in (await db.execute(select(Unit))).scalars().all()}
        total = 0
        for unit_num, types in DATA.items():
            u = units.get(unit_num)
            if not u: continue
            nahw = (await db.execute(select(Lesson).where(
                Lesson.unit_id==u.id, Lesson.lesson_type=="nahw"))).scalar_one_or_none()
            if not nahw: continue
            await db.execute(text(
                "DELETE FROM exercises WHERE lesson_id=:lid AND exercise_type IN ('antonym','plural','synonym','comprehension')"
            ), {"lid": nahw.id})
            num = 800
            for ex_type, items in types.items():
                for q, ans in items:
                    num += 1
                    db.add(Exercise(
                        unit_id=u.id, lesson_id=nahw.id, exercise_number=num,
                        exercise_type=ex_type, question_ar=q, correct_answer=ans,
                        options=None, hint_ar=HINTS[ex_type], difficulty=2, points=10,
                    ))
                    total += 1
            await db.flush()
            print(f"وحدة {unit_num}: تم (20 سؤال)")
        await db.commit()
        print(f"\nتم اضافة {total} سؤالا")

asyncio.run(run())