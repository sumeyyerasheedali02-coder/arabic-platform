HINTS = {"fill_blank":"أكمل الفراغ","translate_ar_tr":"ترجم للتركية"}

async def run():
    async with AsyncSessionLocal() as db:
        units = {u.unit_number: u for u in (await db.execute(select(Unit))).scalars().all()}
        total = 0
        for unit_num, fills in FILL.items():
            u = units.get(unit_num)
            if not u: continue
            nahw = (await db.execute(select(Lesson).where(
                Lesson.unit_id==u.id, Lesson.lesson_type=="nahw"))).scalar_one_or_none()
            if not nahw: continue
            await db.execute(text(
                "DELETE FROM exercises WHERE lesson_id=:lid AND exercise_type IN ('fill_blank','translate_ar_tr')"
            ), {"lid": nahw.id})
            num = 700
            # إكمال فراغ
            for q, ans in fills:
                num += 1
                db.add(Exercise(
                    unit_id=u.id, lesson_id=nahw.id, exercise_number=num,
                    exercise_type="fill_blank", question_ar=q, correct_answer=ans,
                    options=None, hint_ar="أكمل الفراغ", difficulty=2, points=10,
                ))
                total += 1
            # ترجمة: أول 5 مفردات
            vocab = (await db.execute(select(Vocabulary).where(
                Vocabulary.unit_id==u.id).limit(5))).scalars().all()
            for v in vocab:
                num += 1
                db.add(Exercise(
                    unit_id=u.id, lesson_id=nahw.id, exercise_number=num,
                    exercise_type="translate_ar_tr",
                    question_ar=f"ترجم للتركية: {v.word_ar}",
                    correct_answer=v.translation_tr,
                    options=None, hint_ar="ترجم للتركية", difficulty=2, points=10,
                ))
                total += 1
            await db.flush()
            print(f"وحدة {unit_num}: تم")
        await db.commit()
        print(f"\nتم اضافة {total} سؤالا")

asyncio.run(run())